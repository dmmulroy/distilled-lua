// Writes lua/distilled/gcp/regional_endpoints.lua from Distilled's
// packages/gcp/src/regional-endpoints.ts (task 21). Run:
//   node --conditions=bun --experimental-transform-types --no-warnings \
//     verify/lib/gcp_regional_endpoints.mjs <distilled> <out.lua>
import { writeFileSync } from "node:fs";
const [distilled, out] = process.argv.slice(2);
const { REGIONAL_ENDPOINTS } = await import(`${distilled}/packages/gcp/src/regional-endpoints.ts`);
const q = (s) => JSON.stringify(s);
const lines = [
  "-- Regional hosts per Google service, keyed by the service's global base URL (with its",
  "-- trailing /), in preference order (*.rep.googleapis.com first). `template` has a",
  "-- {location} placeholder; `locations` are the ones Google publishes a host for.",
  "--",
  "-- Generated by verify/lib/gcp_regional_endpoints.mjs from Distilled's",
  "-- packages/gcp/src/regional-endpoints.ts (itself generated from the discovery documents'",
  "-- endpoints[]). Do not edit.",
  "return {",
];
for (const base of Object.keys(REGIONAL_ENDPOINTS).sort()) {
  lines.push(`  [${q(base)}] = {`);
  for (const e of REGIONAL_ENDPOINTS[base]) {
    lines.push("    {");
    lines.push(`      template = ${q(e.template)},`);
    lines.push("      locations = {");
    for (const l of e.locations) lines.push(`        ${q(l)},`);
    lines.push("      },");
    lines.push("    },");
  }
  lines.push("  },");
}
lines.push("}");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}: ${Object.keys(REGIONAL_ENDPOINTS).length} services`);
