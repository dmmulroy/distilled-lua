// Writes spec/golden/crypto/vectors.lua: digests, HMACs, base64 and CRC-32 of seeded
// random inputs, computed with node:crypto / Buffer / zlib (the reference). Run through
// `verify/dl crypto-vectors`; the output is deterministic, so re-running it changes
// nothing unless this script changes.
import { createHash, createHmac } from "node:crypto";
import { writeFileSync } from "node:fs";
import zlib from "node:zlib";

const out = process.argv[2];
if (!out) throw new Error("usage: node crypto_vectors.mjs <out.lua>");

// Park-Miller, as distilled.testing.random: same sequence everywhere
let seed = 20260514;
const next = () => (seed = (seed * 16807) % 2147483647);
const bytes = (n) => Buffer.from(Array.from({ length: n }, () => next() % 256));

const HASHES = ["md5", "sha1", "sha224", "sha256", "sha384", "sha512"];
const hex = (b) => Buffer.from(b).toString("hex");
const luaString = (s) => JSON.stringify(s); // hex/base64 text only: JSON quoting is Lua quoting

// lengths around every block boundary (64 and 128 bytes, minus the 9/17 padding bytes)
const lengths = [0, 1, 2, 3, 31, 32, 54, 55, 56, 57, 63, 64, 65, 110, 111, 112, 113, 119, 120,
  127, 128, 129, 183, 191, 192, 200, 255, 256, 257, 300, 511, 512, 513, 1000];
const keyLengths = [0, 1, 16, 20, 32, 63, 64, 65, 100, 127, 128, 129, 200];

const lines = [];
const w = (s) => lines.push(s);
w("-- Generated by verify/lib/crypto_vectors.mjs. Do not edit.");
w("-- Digests, HMACs, base64 and CRC-32 from node:crypto, Buffer and zlib for seeded random inputs.");
w("return {");
w("  digests = {");
for (const n of lengths) {
  const input = bytes(n);
  const fields = HASHES.map((h) => `${h} = ${luaString(createHash(h).update(input).digest("hex"))}`);
  w(`    { input = ${luaString(hex(input))}, ${fields.join(", ")} },`);
}
w("  },");
w("  hmacs = {");
let i = 0;
for (const k of keyLengths) {
  for (const h of ["md5", "sha1", "sha256", "sha512", "sha224", "sha384"]) {
    const key = bytes(k);
    const input = bytes(lengths[i++ % lengths.length]);
    const mac = createHmac(h, key).update(input).digest("hex");
    w(`    { hash = "${h}", key = ${luaString(hex(key))}, input = ${luaString(hex(input))}, mac = ${luaString(mac)} },`);
  }
}
w("  },");
w("  base64 = {");
for (let n = 0; n <= 40; n++) {
  const input = bytes(n);
  w(`    { input = ${luaString(hex(input))}, std = ${luaString(input.toString("base64"))}, url = ${luaString(input.toString("base64url"))} },`);
}
w("  },");
w("  crc32 = {");
for (const n of [0, 1, 3, 4, 5, 100, 255, 256, 257, 1000]) {
  const input = bytes(n);
  w(`    { input = ${luaString(hex(input))}, crc32 = ${zlib.crc32(input)} },`);
}
w("  },");
w("}");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}`);
