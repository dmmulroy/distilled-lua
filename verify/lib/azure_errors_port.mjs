// Writes lua/distilled/azure/errors_data.lua from Distilled's hand-written Azure error
// module (../distilled/packages/azure/src/errors.ts): every Azure error class (tag,
// categories, retryable, whether it declares `target`), AZURE_ERROR_CODE_MAP and
// AZURE_ERROR_MESSAGE_MATCHERS in their order. The classes are read from the loaded
// module (prototype category / retryable keys, the schema's fields), not parsed from
// source, so the Lua data is what Distilled's code does.
//
//   node --conditions=bun --experimental-transform-types --no-warnings \
//     verify/lib/azure_errors_port.mjs lua/distilled/azure/errors_data.lua
// (`verify/dl azure-errors` runs it). DISTILLED_ROOT overrides ../distilled.
import * as path from "node:path";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, "../..");
const DISTILLED = process.env.DISTILLED_ROOT ?? path.resolve(ROOT, "../distilled");
const P = path.join(DISTILLED, "packages");
const E = await import(path.join(P, "azure/src/errors.ts"));
const Core = await import(path.join(P, "core/src/errors.ts"));
const Category = await import(path.join(P, "core/src/category.ts"));

const out = process.argv[2];
if (!out) throw new Error("usage: azure_errors_port.mjs <out.lua>");

const CATEGORY_ORDER = [
  "AuthError",
  "BadRequestError",
  "ConflictError",
  "NotFoundError",
  "QuotaError",
  "ServerError",
  "ThrottlingError",
  "NetworkError",
  "ParseError",
  "ConfigurationError",
  "TimeoutError",
  "RetryableError",
  "LockedError",
  "AbortedError",
  "AlreadyExistsError",
  "DependencyViolationError",
];

const tagOf = (C) => new C({})._tag;
const coreClasses = new Set(Object.values(Core).filter((v) => typeof v === "function"));

// every Azure-own error class the module exports (core re-exports excluded)
const classes = new Map();
for (const [name, v] of Object.entries(E)) {
  if (typeof v !== "function" || coreClasses.has(v) || !v.fields) continue;
  if (name === "UnknownAzureError" || name === "AzureParseError") continue;
  const tag = tagOf(v);
  if (tag !== name) throw new Error(`class ${name} has tag ${tag}`);
  const cats = v.prototype[Category.categoriesKey] ?? {};
  const retry = v.prototype[Category.retryableKey];
  const fields = Object.keys(v.fields);
  for (const f of fields) {
    if (!["message", "code", "target"].includes(f)) throw new Error(`${name}: field ${f}`);
  }
  classes.set(v, {
    tag,
    categories: CATEGORY_ORDER.filter((c) => cats[c]),
    retryable: retry !== undefined,
    throttling: retry?.throttling === true,
    target: fields.includes("target"),
  });
}
const unknownCats = Object.keys(E.UnknownAzureError.prototype[Category.categoriesKey] ?? {});
if (unknownCats.length) throw new Error("UnknownAzureError has categories");

// a JSON string is a Lua string literal once \uXXXX escapes (control characters) are
// spelled as Lua 5.1's decimal escapes
const lua = (s) =>
  JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => {
    const n = parseInt(h, 16);
    if (n > 127) throw new Error("non-ASCII escape");
    return "\\" + String(n).padStart(3, "0");
  });
const tagFor = (C) => {
  const c = classes.get(C);
  if (!c) throw new Error(`not an Azure class: ${C?.name}`);
  return c.tag;
};

const lines = [];
const add = (s = "") => lines.push(s);
add("-- Generated by verify/lib/azure_errors_port.mjs from Distilled's");
add("-- packages/azure/src/errors.ts. Do not edit; regenerate with `verify/dl azure-errors`.");
add("--");
add("-- classes: { tag, categories, retryable, throttling, target } sorted by tag;");
add("-- `target = true` when the class declares `target` (AzureErrorFields), false for the");
add("-- auth classes that declare only message and code (AzureAuthErrorFields).");
add("-- codes: AZURE_ERROR_CODE_MAP (ARM error.code -> tag).");
add("-- matchers: AZURE_ERROR_MESSAGE_MATCHERS in order ({ code?, includes, tag }).");
add("return {");
add("  classes = {");
for (const c of classes.values()) {
  const parts = [`tag = ${lua(c.tag)}`];
  parts.push(`categories = { ${c.categories.map(lua).join(", ")} }`);
  if (c.retryable) parts.push("retryable = true");
  if (c.throttling) parts.push("throttling = true");
  parts.push(`target = ${c.target}`);
  add(`    { ${parts.join(", ")} },`);
}
add("  },");
add("  codes = {");
for (const code of Object.keys(E.AZURE_ERROR_CODE_MAP).sort()) {
  add(`    [${lua(code)}] = ${lua(tagFor(E.AZURE_ERROR_CODE_MAP[code]))},`);
}
add("  },");
add("  matchers = {");
for (const m of E.AZURE_ERROR_MESSAGE_MATCHERS) {
  const keys = Object.keys(m).filter((k) => !["code", "includes", "error"].includes(k));
  if (keys.length) throw new Error(`matcher with keys ${keys}`);
  const parts = [];
  if (m.code !== undefined) parts.push(`code = ${lua(m.code)}`);
  parts.push(`includes = ${lua(m.includes)}`);
  parts.push(`tag = ${lua(tagFor(m.error))}`);
  add(`    { ${parts.join(", ")} },`);
}
add("  },");
add("}");
writeFileSync(out, lines.join("\n") + "\n");
console.log(
  `wrote ${out}: ${classes.size} classes, ${Object.keys(E.AZURE_ERROR_CODE_MAP).length} codes, ` +
    `${E.AZURE_ERROR_MESSAGE_MATCHERS.length} matchers`,
);
