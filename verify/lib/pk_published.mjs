// Writes spec/golden/crypto_pk/published.lua: public-key test vectors copied out of their
// publications, so the spec can quote them without a hand-typed hex string:
//
//   RFC 6979 A.2.5  ECDSA P-256 with SHA-1/224/256/384/512, messages "sample" and "test"
//   RFC 8032 7.1    Ed25519 TEST 1, 2, 3, 1024 and SHA(abc)
//   RFC 7515 A.2/3  the RS256 and ES256 example JWSs and their JWKs
//   RFC 8037 A      the Ed25519 JWK, its thumbprint and the EdDSA JWS
//   tiny-secp256k1  tests/fixtures/ecdsa.json (bitcoinjs): RFC 6979 secp256k1 signatures
//                   with low S and recovery ids, the first 32 "valid" cases
//
// Run through `verify/dl pk-vectors` (needs the network: it fetches the documents from
// rfc-editor.org and GitHub). The output is deterministic.
import { writeFileSync } from "node:fs";

const out = process.argv[2];
if (!out) throw new Error("usage: node pk_published.mjs <out.lua>");

const TINY =
  "https://raw.githubusercontent.com/bitcoinjs/tiny-secp256k1/v2.2.3/tests/fixtures/ecdsa.json";
const rfc = (n) => `https://www.rfc-editor.org/rfc/rfc${n}.txt`;

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};

// RFC text without page breaks (footer, form feed, header)
const clean = (text) =>
  text
    .split("\n")
    .filter((l) => !/^\S.*\[Page \d+\]$/.test(l) && !/^RFC \d+ /.test(l) && l !== "\f")
    .map((l) => l.replace(/\f/g, ""))
    .join("\n");

const section = (text, start, end) => {
  const i = text.indexOf(start, text.indexOf(start) + 1) >= 0 ? text.lastIndexOf(start) : -1;
  if (i < 0) throw new Error(`section ${start} not found`);
  const j = text.indexOf(end, i + start.length);
  return text.slice(i, j < 0 ? undefined : j);
};

const q = (s) => JSON.stringify(s);
const lines = [];
const w = (s) => lines.push(s);

const [t6979, t8032, t7515, t8037, tiny] = await Promise.all([
  get(rfc(6979)).then(clean),
  get(rfc(8032)).then(clean),
  get(rfc(7515)).then(clean),
  get(rfc(8037)).then(clean),
  get(TINY).then(JSON.parse),
]);

w("-- Generated by verify/lib/pk_published.mjs from the documents it names. Do not edit.");
w("return {");

// RFC 6979 A.2.5
{
  const s = section(t6979, "A.2.5.  ECDSA, 256 Bits (Prime Field)", "A.2.6.");
  const val = (name) => s.match(new RegExp(`${name} = ([0-9A-F]+)`))[1].toLowerCase();
  w(`  rfc6979_p256 = {`);
  w(`    x = ${q(val("x"))}, ux = ${q(val("Ux"))}, uy = ${q(val("Uy"))},`);
  w(`    signatures = {`);
  const re = /With SHA-(\d+), message = "(\w+)":\s+k = ([0-9A-F]+)\s+r = ([0-9A-F]+)\s+s = ([0-9A-F]+)/g;
  for (const m of s.matchAll(re)) {
    const hash = m[1] === "1" ? "sha1" : `sha${m[1]}`;
    w(
      `      { hash = ${q(hash)}, message = ${q(m[2])}, k = ${q(m[3].toLowerCase())}, r = ${q(m[4].toLowerCase())}, s = ${q(m[5].toLowerCase())} },`,
    );
  }
  w(`    },`);
  w(`  },`);
}

// RFC 8032 7.1
{
  const s = section(t8032, "7.1.  Test Vectors for Ed25519", "7.2.");
  w(`  rfc8032 = {`);
  for (const block of s.split("-----TEST ").slice(1)) {
    const name = block.split("\n")[0].trim();
    const field = (label, next) => {
      const i = block.indexOf(label);
      const rest = block.slice(block.indexOf("\n", i) + 1);
      const j = next ? rest.indexOf(next) : rest.indexOf("-----");
      return rest.slice(0, j < 0 ? undefined : j).replace(/\s+/g, "");
    };
    const message = field("MESSAGE", "SIGNATURE:");
    const signature = field("SIGNATURE:");
    w(
      `    { name = ${q(name)}, secret = ${q(field("SECRET KEY:", "PUBLIC KEY:"))}, public = ${q(field("PUBLIC KEY:", "MESSAGE"))}, message = ${q(message)}, signature = ${q(signature)} },`,
    );
  }
  w(`  },`);
}

// RFC 7515 A.2 (RS256) and A.3 (ES256): the JWK and the compact JWS
{
  const jwk = (s) => JSON.parse(s.match(/\{"kty"[\s\S]*?\n\s*\}/)[0].replace(/\s+/g, ""));
  const compact = (s) => {
    const i = s.indexOf("representation using the JWS Compact Serialization");
    const body = s.slice(s.indexOf("\n", s.indexOf("only):", i)) + 1);
    const end = body.search(/\n[A-Z]\.\d/);
    return body.slice(0, end).replace(/\s+/g, "");
  };
  const a2 = section(t7515, "A.2.  Example JWS Using RSASSA-PKCS1-v1_5 SHA-256", "A.2.2.");
  const a3 = section(t7515, "A.3.  Example JWS Using ECDSA P-256 SHA-256", "A.3.2.");
  w(`  rfc7515 = {`);
  w(`    rs256 = { jwk = ${q(JSON.stringify(jwk(a2)))}, jws = ${q(compact(a2))} },`);
  w(`    es256 = { jwk = ${q(JSON.stringify(jwk(a3)))}, jws = ${q(compact(a3))} },`);
  w(`  },`);
}

// RFC 8037 appendix A
{
  const a1 = section(t8037, "A.1.  Ed25519 Private Key", "A.2.");
  const a3 = section(t8037, "A.3.  JWK Thumbprint Canonicalization", "A.4.");
  const a4 = section(t8037, "A.4.  Ed25519 Signing", "A.5.");
  const key = JSON.parse(a1.match(/\{"kty"[\s\S]*?\}/)[0].replace(/\s+/g, ""));
  const thumb = a3.match(/representation\s+of "([\w-]+)"/)[1];
  const canon = a3.match(/\{"crv"[\s\S]*?\}/)[0].replace(/\s+/g, "");
  const jwsText = a4.slice(a4.indexOf("So the compact serialization"));
  const jws = jwsText
    .slice(jwsText.indexOf("):") + 2)
    .trim()
    .replace(/\s+/g, "");
  w(`  rfc8037 = {`);
  w(`    jwk = ${q(JSON.stringify(key))},`);
  w(`    canonical = ${q(canon)},`);
  w(`    thumbprint = ${q(thumb)},`);
  w(`    payload = "Example of Ed25519 signing",`);
  w(`    jws = ${q(jws)},`);
  w(`  },`);
}

// tiny-secp256k1
{
  w(`  secp256k1 = {`);
  for (const v of tiny.valid.slice(0, 32)) {
    w(
      `    { d = ${q(v.d)}, m = ${q(v.m)}, signature = ${q(v.signature)}, recovery_id = ${v.recoveryId} },`,
    );
  }
  w(`  },`);
}

w("}");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}`);
