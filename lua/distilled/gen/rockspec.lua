-- LuaRocks packaging: the text of a rockspec for the runtime or for one generated client.
--
--   local rockspec = require("distilled.gen.rockspec")
--   local rock = rockspec.runtime_rockspec({ version = "0.1.0", files = runtime_files })
--   local rock = rockspec.client_rockspec({ version = "0.1.0", provider = "twitch",
--     title = "Twitch", files = { "clients/twitch/init.lua", ... } })
--   -- rock = { name, version, rockspec_file, archive_name, text, files }
--
-- Rocks:
--   distilled              lua/distilled/ without gen/ and testing/ (what `vendor` copies)
--   distilled-<provider>   clients/<provider>/, installed as modules
--                          distilled.clients.<provider>.* so that generic names such as
--                          `aws` or `twitch` stay free for other rocks. Generated clients
--                          find their own modules from `...`, so the same files load under
--                          that prefix unchanged.
-- Each rock's source is its own archive (a GitHub release asset), not the git repository:
-- clients/ is hundreds of megabytes, and a rock built from a git URL clones all of it.
-- The archive keeps the repository's paths, so the same rockspec also works with
-- `luarocks make` from a checkout. No I/O here; bin/distilled-lua lists and writes files.

local M = {}

M.ROCKSPEC_REVISION = 1
M.HOMEPAGE = "https://github.com/dmmulroy/distilled-lua"
M.LICENSE = "Apache-2.0"
M.CLIENT_MODULE_PREFIX = "distilled.clients."

local function lua_string(s)
  return string.format("%q", s)
end

--- The rock name of a provider's client: "boat_dev" -> "distilled-boat-dev".
function M.client_rock_name(provider)
  return "distilled-" .. (string.gsub(provider, "_", "-"))
end

--- The module a file provides, from its path under `strip` ("lua/" or "clients/"):
--- "clients/twitch/chat/init.lua" with prefix "distilled.clients." -> "distilled.clients.twitch.chat".
function M.module_of_file(path, strip, prefix)
  local rel = string.sub(path, #strip + 1)
  rel = string.gsub(rel, "%.lua$", "")
  rel = string.gsub(rel, "/init$", "")
  return (prefix or "") .. (string.gsub(rel, "/", "."))
end

local function valid_version(version)
  return type(version) == "string" and string.find(version, "^%d+%.%d+%.%d+$") ~= nil
end

local function render(o)
  local full_version = o.version .. "-" .. M.ROCKSPEC_REVISION
  local archive_dir = o.name .. "-" .. o.version
  local archive_name = archive_dir .. ".tar.gz"
  local lines = {
    "-- Generated by distilled-lua (bin/distilled-lua rockspec). Do not edit.",
    'rockspec_format = "3.0"',
    "package = " .. lua_string(o.name),
    "version = " .. lua_string(full_version),
    "source = {",
    "  url = " .. lua_string(
      M.HOMEPAGE .. "/releases/download/v" .. o.version .. "/" .. archive_name
    ) .. ",",
    "  dir = " .. lua_string(archive_dir) .. ",",
    "}",
    "description = {",
    "  summary = " .. lua_string(o.summary) .. ",",
    "  detailed = " .. lua_string(o.detailed) .. ",",
    "  homepage = " .. lua_string(M.HOMEPAGE) .. ",",
    "  license = " .. lua_string(M.LICENSE) .. ",",
    "  labels = { " .. table.concat(o.labels, ", ") .. " },",
    "}",
    "dependencies = {",
  }
  for _, dependency in ipairs(o.dependencies) do
    lines[#lines + 1] = "  " .. lua_string(dependency) .. ","
  end
  lines[#lines + 1] = "}"
  lines[#lines + 1] = "build = {"
  lines[#lines + 1] = '  type = "builtin",'
  lines[#lines + 1] = "  modules = {"
  local modules, seen = {}, {}
  for _, path in ipairs(o.files) do
    local module = M.module_of_file(path, o.strip, o.prefix)
    if seen[module] then
      return nil, "two files give module " .. module .. ": " .. seen[module] .. " and " .. path
    end
    seen[module] = path
    modules[#modules + 1] = { module, path }
  end
  table.sort(modules, function(a, b)
    return a[1] < b[1]
  end)
  for _, entry in ipairs(modules) do
    lines[#lines + 1] = "    [" .. lua_string(entry[1]) .. "] = " .. lua_string(entry[2]) .. ","
  end
  lines[#lines + 1] = "  },"
  lines[#lines + 1] = "}"
  local files = {}
  for index, path in ipairs(o.files) do
    files[index] = path
  end
  -- every archive carries the license
  files[#files + 1] = "LICENSE"
  files[#files + 1] = "NOTICE"
  return {
    name = o.name,
    version = full_version,
    rockspec_file = o.name .. "-" .. full_version .. ".rockspec",
    archive_name = archive_name,
    archive_dir = archive_dir,
    text = table.concat(lines, "\n") .. "\n",
    files = files,
  }
end

--- The runtime rock. opts: version ("0.1.0"), files (paths under lua/distilled/).
function M.runtime_rockspec(opts)
  if not valid_version(opts.version) then
    return nil, "version must be MAJOR.MINOR.PATCH, got " .. tostring(opts.version)
  end
  return render({
    name = "distilled",
    version = opts.version,
    summary = "Runtime for distilled-lua's generated API clients",
    detailed = "Typed errors, retries, pagination, streaming, request signing and the HTTP "
      .. "transports used by the distilled-clients rocks. Pure Lua 5.1, runs on PUC Lua 5.1 "
      .. "to 5.5, LuaJIT and gopher-lua (Rex).",
    labels = { '"api"', '"http"', '"sdk"' },
    dependencies = { "lua >= 5.1" },
    files = opts.files,
    strip = "lua/",
  })
end

--- A provider's client rock. opts: version, provider ("twitch"), title ("Twitch"),
--- files (paths under clients/<provider>/, .lua only).
function M.client_rockspec(opts)
  if not valid_version(opts.version) then
    return nil, "version must be MAJOR.MINOR.PATCH, got " .. tostring(opts.version)
  end
  if not string.find(opts.provider or "", "^[a-z][a-z0-9_]*$") then
    return nil, "provider must be a lowercase Lua name, got " .. tostring(opts.provider)
  end
  local title = opts.title or opts.provider
  return render({
    name = M.client_rock_name(opts.provider),
    version = opts.version,
    summary = title .. " API client, generated by distilled-lua",
    detailed = 'require("'
      .. M.CLIENT_MODULE_PREFIX
      .. opts.provider
      .. '"). Generated from '
      .. "Distilled's model of the "
      .. title
      .. " API: each operation has a known input, "
      .. "output and error list. Errors are values; a failed request never raises.",
    labels = { '"api"', '"sdk"', lua_string(opts.provider) },
    dependencies = { "lua >= 5.1", "distilled == " .. opts.version },
    files = opts.files,
    strip = "clients/",
    prefix = M.CLIENT_MODULE_PREFIX,
  })
end

return M
